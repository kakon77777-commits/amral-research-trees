def check_exponent_chain(data: dict) -> dict:
    rho = Fraction(data["rho_star"])
    mu = rho + 1
    theta = 1 / mu
    sigma = 1 / (1 + theta)
    congestion = 1 - sigma

    identities = {
        "mu_star == rho_star + 1": Fraction(data["mu_star"]) == mu,
        "theta_star * mu_star == 1": theta * mu == 1,
        "sigma_star * (1 + theta_star) == 1": sigma * (1 + theta) == 1,
        "sigma_star + congestion == 1": sigma + congestion == 1,
        "rho_star is conservative against the cited exponent":
            rho > Fraction(CITED_EXPONENT),
        "the cited exponent improves on Rhin's":
            Fraction(CITED_EXPONENT) < Fraction(RHIN_EXPONENT),
        "theta_star < 1": theta < 1,
        "sigma_star < 1": sigma < 1,
        "congestion > 0": congestion > 0,
    }
    published = {
        "theta_star": (data["theta_star"], theta),
        "sigma_star": (data["sigma_star"], sigma),
        "congestion_exponent": (data["congestion_exponent"], congestion),
    }
    verdicts = {k: rational_verdict(text, exact) for k, (text, exact) in published.items()}
    return {
        "rho_star_as_an_exact_rational": "%d/%d" % (rho.numerator, rho.denominator),
        "cited_exponent": CITED_EXPONENT,
        "rho_star_minus_cited": str(rho - Fraction(CITED_EXPONENT)),
        "theta_star_exact": "%d/%d" % (theta.numerator, theta.denominator),
        "sigma_star_exact": "%d/%d" % (sigma.numerator, sigma.denominator),
        "congestion_exact": "%d/%d" % (congestion.numerator, congestion.denominator),
        "identities": identities,
        "published_digits": verdicts,
        "all_identities_hold": all(identities.values()),
        "wrong_digits": sorted(k for k, v in verdicts.items() if v["verdict"] == "WRONG"),
    }


