# section 7 — the elementary inequalities the derivation leans on
# ---------------------------------------------------------------------------

def check_inequalities() -> dict:
    with mp.workdps(60):
        ln2 = mp.log(2)
        rng = random.Random(20260823)

        # 2^D - 1 >= (ln 2) D  for D >= 0, used at section 4
        a_fail, a_tight = 0, 0
        for _ in range(4000):
            D = mp.mpf(rng.random()) * 4
            if 2 ** D - 1 < ln2 * D - mp.mpf(10) ** -40:
                a_fail += 1
            if abs(2 ** D - 1 - ln2 * D) < mp.mpf("1e-3"):
                a_tight += 1
        equality_at_zero = abs(2 ** mp.mpf(0) - 1 - ln2 * 0) < mp.mpf(10) ** -50

        # 2^{gd} - 1 >= g (2^d - 1)  for integer g >= 1, d > 0, used at section 7
        b_fail, b_equal = 0, 0
        for _ in range(4000):
            g = rng.randint(1, 40)
            d = mp.mpf(rng.random()) * 2 + mp.mpf("1e-9")
            lhs, rhs = 2 ** (g * d) - 1, g * (2 ** d - 1)
            if lhs < rhs - mp.mpf(10) ** -40:
                b_fail += 1
            if g == 1 and abs(lhs - rhs) < mp.mpf(10) ** -50:
                b_equal += 1

        # Q alpha - L = alpha D given Q = beta L + D and alpha beta = 1  (section 3)
        beta = mp.log(3, 2)
        alpha = 1 / beta
        c_fail = 0
        for _ in range(2000):
            L = mp.mpf(rng.randint(1, 10 ** 6))
            D = mp.mpf(rng.random())
            Q = beta * L + D
            if abs((Q * alpha - L) - alpha * D) > mp.mpf(10) ** -40:
                c_fail += 1

        # D <= log2(1 + L/(3y)) < 1 when L < y  (section 3)
        d_fail, d_max = 0, mp.mpf(0)
        for _ in range(2000):
            y = mp.mpf(rng.randint(3, 10 ** 9))
            L = mp.mpf(rng.randint(1, int(y) - 1))
            cap = mp.log(1 + L / (3 * y), 2)
            d_max = max(d_max, cap)
            if cap >= 1:
                d_fail += 1

    return {
        "2^D - 1 >= (ln2) D": {"samples": 4000, "violations": a_fail,
                               "samples_within_1e-3_of_equality": a_tight,
                               "equality_at_D=0": bool(equality_at_zero)},
        "2^(gd) - 1 >= g (2^d - 1)": {"samples": 4000, "violations": b_fail,
                                      "exact_equalities_at_g=1": b_equal},
        "Q alpha - L == alpha D": {"samples": 2000, "violations": c_fail},
        "D < 1 whenever L < y": {"samples": 2000, "violations": d_fail,
                                 "largest_cap_seen": mp.nstr(d_max, 8),
                                 "log2(4/3)": mp.nstr(mp.log(mp.mpf(4) / 3, 2), 8)},
        "violations": a_fail + b_fail + c_fail + d_fail,
    }


