def rational_digits(value: Fraction, places: int) -> str:
    """Exact decimal expansion, truncated to `places` digits after the point."""
    sign = "-" if value < 0 else ""
    value = abs(value)
    whole = value.numerator // value.denominator
    rest = value - whole
    num, den = rest.numerator, rest.denominator
    out = []
    for _ in range(places):
        num *= 10
        digit, num = divmod(num, den)
        out.append(str(digit))
    return "%s%d.%s" % (sign, whole, "".join(out))


def leading_agreement(published: str, reference: str) -> int:
    """How many characters of `published` a longer `reference` agrees with."""
    n = 0
    for a, b in zip(published, reference):
        if a != b:
            break
        n += 1
    return n


def decimals_published(text: str) -> int:
    return len(text.split(".")[1]) if "." in text else 0


def decimal_verdict(published: str, reference: str) -> dict:
    """Is a published decimal exact, its correct rounding, or actually wrong?

    ONE implementation, because the distinction is easy to get wrong in the
    ACCUSING direction and getting it wrong twice is how a run publishes a
    finding against correct arithmetic. Two ways to get it wrong, both met here
    while writing this file:

      * comparing against a TRUNCATION calls a correctly-rounded last digit an
        error;
      * checking the reference digit AT the last published position instead of
        the one AFTER it misses the carry -- `...173219729` correctly rounds to
        `...17322`, and reading the `1` rather than the `9` calls that wrong.

    So round once, properly, with exact rational arithmetic, and compare.
    `reference` must be a decimal string with strictly more digits than
    `published`, from a computation far more precise than the artifact's.
    """
    places = decimals_published(published)
    ref = Fraction(reference)
    scale = 10 ** places
    truncated = Fraction(int(ref * scale), scale)
    remainder = ref * scale - int(ref * scale)
    rounded = truncated + (Fraction(1, scale) if remainder >= Fraction(1, 2)
                           else Fraction(0))
    shown = Fraction(published)
    if shown == truncated == rounded:
        return {"published_decimals": places, "digits_correct": places,
                "verdict": "exact to every published digit"}
    if shown == rounded:
        return {"published_decimals": places, "digits_correct": places,
                "verdict": "correctly rounded at the last digit"}
    if shown == truncated:
        return {"published_decimals": places, "digits_correct": places,
                "verdict": "truncated rather than rounded at the last digit"}
    agree = leading_agreement(published, reference)
    correct = max(0, agree - (published.index(".") + 1))
    return {"published_decimals": places, "digits_correct": correct,
            "verdict": "OVER-PUBLISHED",
            "digits_beyond_the_computation": places - correct,
            "published_tail": published[-16:],
            "reference_tail": reference[max(0, len(published) - 16):len(published) + 4]}


def rational_verdict(published: str, exact: Fraction) -> dict:
    """Same comparison, but the verdict for a RATIONAL cannot be over-publication.

    A transcendental printed past its working precision has an excuse. A
    quantity that is exactly `2500/12791` has none: every digit is available, so
    a mismatch beyond the last-digit rounding is simply wrong. Until this
    distinction was drawn, `wrong_digits` was a list the gate reported and gated
    on that no input could ever fill.
    """
    places = decimals_published(published)
    verdict = decimal_verdict(published, rational_digits(exact, places + 12))
    if verdict["verdict"] == "OVER-PUBLISHED":
        verdict["verdict"] = "WRONG"
        verdict.pop("digits_beyond_the_computation", None)
    return verdict


def mpf_verdict(published: str, value) -> dict:
    places = decimals_published(published)
    with mp.workdps(WORKING_DPS):
        integer_digits = len(mp.nstr(value, 5).split(".")[0].lstrip("-"))
        if abs(value) < 1:
            integer_digits = 0
        reference = mp.nstr(value, places + integer_digits + 12, strip_zeros=False)
    if "." not in reference:                                # pragma: no cover
        reference += ".0"
    if len(reference.split(".")[1]) <= places:              # pragma: no cover
        reference = mp.nstr(value, places + integer_digits + 20, strip_zeros=False)
    return decimal_verdict(published, reference)


