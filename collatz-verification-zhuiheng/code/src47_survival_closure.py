# section 4 — the continued-fraction tax, and the upper-convergent filter
# ---------------------------------------------------------------------------

def beta_enclosure(terms: list[int], want: int) -> tuple[Fraction, Fraction]:
    """An exact rational bracket for log_2 3 from certified partial quotients."""
    conv = convergents_from_terms(terms)
    pick = [c for c in conv if c[0] >= want][-2:] or conv[-2:]
    (i1, p1, q1), (i2, p2, q2) = pick[-2], pick[-1]
    lo, hi = Fraction(p1, q1), Fraction(p2, q2)
    return (lo, hi) if lo < hi else (hi, lo)


def check_cf_tax(data: dict, cf: dict) -> dict:
    """1/(q+q+) < p - beta q < 1/q+ on every shipped upper convergent.

    Decided as a comparison of exact rationals wherever the bracket certifies it,
    and reported as undecided rather than rounded when it does not.
    """
    terms = cf["certified_partial_quotients"]
    lo, hi = beta_enclosure(terms, want=len(terms) - 2)
    rows, undecided, violations = [], [], []
    for row in data["upper_convergent_diagnostics"]:
        p, q, qn = row["p"], row["q"], row["q_next"]
        err_lo, err_hi = p - hi * q, p - lo * q          # exact interval for p-beta*q
        lower, upper = Fraction(1, q + qn), Fraction(1, qn)
        decided_lower = err_lo > lower or err_hi <= lower
        decided_upper = err_hi < upper or err_lo >= upper
        holds_lower = err_lo > lower
        holds_upper = err_hi < upper
        positive = err_lo > 0
        entry = {"index": row["index"], "q": q,
                 "lower_bound_decided": bool(decided_lower),
                 "upper_bound_decided": bool(decided_upper),
                 "1/(q+q+) < p-beta q": bool(holds_lower) if decided_lower else None,
                 "p-beta q < 1/q+": bool(holds_upper) if decided_upper else None,
                 "p/q is above beta": bool(positive) if (err_lo > 0 or err_hi < 0) else None}
        rows.append(entry)
        if not (decided_lower and decided_upper):
            undecided.append(row["index"])
        else:
            if not holds_lower or not holds_upper:
                violations.append(entry)
    # The rows the exact bracket cannot judge are not left silent. They are
    # decided at four times the artifact's precision and reported SEPARATELY,
    # because "checked exactly" and "checked well" are different claims.
    with mp.workdps(WORKING_DPS):
        beta = mp.log(3, 2)
        hp_violations = []
        for row in data["upper_convergent_diagnostics"]:
            p, q, qn = row["p"], row["q"], row["q_next"]
            err = mp.mpf(p) - beta * q
            if not (mp.mpf(1) / (q + qn) < err < mp.mpf(1) / qn):
                hp_violations.append(row["index"])
    return {
        "beta_bracket_width": mp.nstr(mp.mpf(float(hi - lo)), 4),
        "rows": rows,
        "rows_decided_exactly": sum(1 for r in rows
                                    if r["lower_bound_decided"] and r["upper_bound_decided"]),
        "rows_the_exact_bracket_cannot_judge": undecided,
        "violations": violations,
        "violations_at_400_dps_over_every_row": hp_violations,
        "every_row_holds_by_one_route_or_the_other":
            not violations and not hp_violations,
    }


def check_upper_filter(data: dict, cf: dict) -> dict:
    """The script keeps rows with `err > 0`. Check BOTH directions.

    A filter is only verified when the things it dropped are checked too --
    otherwise one that silently drops half the valid rows still passes.

    Which side of beta a convergent falls on is decided by PARITY, not by the
    numeric bracket: convergents alternate, so with `a_0 = 1 < beta` the odd
    indices lie above. A first version asked the bracket instead and reported
    index 13 as undecided -- because the bracket is built FROM convergents 13
    and 14, so its width is exactly the quantity it was being asked to resolve.
    A test that cannot decide its own last case is measuring its own input. The
    parity rule gives the verdict; the bracket now only CONFIRMS it, wherever it
    is tight enough to have an opinion.
    """
    terms = cf["certified_partial_quotients"]
    lo, hi = beta_enclosure(terms, want=len(terms) - 2)
    kept = {row["index"] for row in data["upper_convergent_diagnostics"]}
    conv = convergents_from_terms(terms)

    above = [i for i, _, _ in conv[:-1] if i % 2 == 1]
    below = [i for i, _, _ in conv[:-1] if i % 2 == 0]

    confirmed, contradicted, silent = 0, [], 0
    for i, p, q in conv[:-1]:
        err_lo, err_hi = p - hi * q, p - lo * q
        if err_lo > 0:
            side = "above"
        elif err_hi < 0:
            side = "below"
        else:
            silent += 1
            continue
        if (side == "above") != (i % 2 == 1):
            contradicted.append(i)
        else:
            confirmed += 1

    limit = max(kept)
    expected = [i for i in above if i <= limit]
    wrongly_dropped = sorted(set(expected) - kept)
    wrongly_kept = sorted(i for i in kept if i in set(below))
    return {
        "side_decided_by": "parity of the convergent index",
        "indices_above_beta_up_to_the_last_shipped_row": expected,
        "indices_below_beta": [i for i in below if i <= limit],
        "shipped_indices": sorted(kept),
        "above_beta_but_missing_from_the_JSON": wrongly_dropped,
        "below_beta_but_present_in_the_JSON": wrongly_kept,
        "parity_confirmed_by_the_exact_bracket_on": confirmed,
        "parity_contradicted_by_the_exact_bracket_on": contradicted,
        "indices_the_bracket_is_too_wide_to_judge": silent,
        "the_filter_is_right_in_both_directions":
            not wrongly_dropped and not wrongly_kept and not contradicted,
    }


