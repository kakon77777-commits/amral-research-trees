def significant_digits(published: str, reference: str) -> tuple[int, int]:
    """(published, correct) counted in SIGNIFICANT digits, not decimal places.

    `p - beta*q` is around `1e-10` for the large convergents, so a tenth of the
    string is leading zeros. Counting decimals there would flatter the artifact
    on the small rows and punish it on the large ones.
    """
    lead = published.index(".") + 1
    zeros = len(published[lead:]) - len(published[lead:].lstrip("0"))
    shown = len(published) - lead - zeros
    correct = max(0, leading_agreement(published, reference) - lead - zeros)
    return shown, min(correct, shown)


def check_row_arithmetic(data: dict) -> dict:
    """Recompute every published row field, and PREDICT where precision runs out.

    "Over-published" on its own is a label. The useful form is a number a reader
    can re-derive: mpmath keeps about `dps` significant digits, so subtracting
    two quantities of size `beta*q` to get one of size `1/q+` costs about
    `log10(beta * q * q+)` of them. That prediction is checked against the
    measured agreement here, so the finding carries its own mechanism instead of
    an adjective.
    """
    with mp.workdps(WORKING_DPS):
        ln2 = mp.log(2)
        eta = 1 / (6 * ln2)
        kappa = 1 / (12 * mp.sqrt(2))
        beta = mp.log(3, 2)
        rows, worst, mispredicted = [], None, []
        for row in data["upper_convergent_diagnostics"]:
            q_i, qn_i, p_i = row["q"], row["q_next"], row["p"]
            q, qn, pv = mp.mpf(q_i), mp.mpf(qn_i), mp.mpf(p_i)
            first = (q + qn) * (eta * q + mp.mpf(1) / 3) / ln2
            bracket = eta * q + mp.mpf(1) / 3 - kappa * mp.sqrt(q)
            second = (q + qn) * bracket / ln2 if bracket > 0 else mp.mpf(0)
            err = pv - beta * q

            fields = {
                "first_order_height_capacity": first,
                "second_order_height_capacity_diagnostic": second,
                "primitive_error": err,
            }
            verdicts, shown_correct = {}, {}
            for name, value in fields.items():
                published = row[name]
                verdicts[name] = mpf_verdict(published, value)["verdict"]
                places = decimals_published(published)
                integer_digits = 0 if abs(value) < 1 else len(
                    mp.nstr(value, 5).split(".")[0].lstrip("-"))
                reference = mp.nstr(value, places + integer_digits + 12,
                                    strip_zeros=False)
                shown_correct[name] = significant_digits(published, reference)

            shown, correct = shown_correct["primitive_error"]
            predicted = shown - float(mp.log(beta * q * qn, 10)) if q_i * qn_i > 1 else shown
            rows.append({
                "index": row["index"], "q": q_i, "q_next": qn_i,
                "verdicts": verdicts,
                "primitive_error_significant_digits_published": shown,
                "primitive_error_significant_digits_correct": correct,
                "predicted_from_cancellation": round(predicted, 1),
                "prediction_error": round(correct - predicted, 1),
                "capacity_fields_fully_correct": all(
                    verdicts[k] != "OVER-PUBLISHED"
                    for k in ("first_order_height_capacity",
                              "second_order_height_capacity_diagnostic")),
            })
            # the prediction must be conservative and close; if it ran ahead of
            # the measurement the mechanism claimed here is the wrong one
            if not (-0.5 <= correct - predicted <= 4.0):
                mispredicted.append(row["index"])
            if worst is None or correct < worst:
                worst = correct

    bad = [r["index"] for r in rows if any(v == "WRONG" for v in r["verdicts"].values())]
    over = [r["index"] for r in rows
            if any(v == "OVER-PUBLISHED" for v in r["verdicts"].values())]
    over_fields = sorted({k for r in rows for k, v in r["verdicts"].items()
                          if v == "OVER-PUBLISHED"})
    return {
        "rows": rows,
        "fewest_significant_digits_correct": worst,
        "rows_with_a_wrong_value": bad,
        "rows_over_published": over,
        "fields_ever_over_published": over_fields,
        "capacity_fields_over_published_anywhere":
            any(f != "primitive_error" for f in over_fields),
        "rows_where_the_cancellation_model_mispredicts": mispredicted,
    }


