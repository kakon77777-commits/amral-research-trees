def check_artifact_provenance(bundle: pathlib.Path, data: dict) -> dict:
    source = (bundle / VERIFY_SCRIPT).read_text(encoding="utf-8")
    body = source[source.index("data = {"):]
    top = re.findall(r'"([A-Za-z_0-9]+)":', body[:body.index("}")])
    row_src = source[source.index("upper_rows.append({"):]
    row_keys = re.findall(r'"([A-Za-z_0-9]+)":', row_src[:row_src.index("})")])

    json_top = list(data.keys())
    json_rows = list(data["upper_convergent_diagnostics"][0].keys())
    missing_top = [k for k in top if k not in json_top]
    extra_top = [k for k in json_top if k not in top]
    missing_row = [k for k in row_keys if k not in json_rows]
    extra_row = [k for k in json_rows if k not in row_keys]
    return {
        "script_top_level_keys": top,
        "json_top_level_keys": json_top,
        "script_row_keys": row_keys,
        "json_row_keys": json_rows,
        "top_level_keys_in_script_but_not_json": missing_top,
        "top_level_keys_in_json_but_not_script": extra_top,
        "row_keys_in_script_but_not_json": missing_row,
        "row_keys_in_json_but_not_script": extra_row,
        "json_was_produced_by_this_script":
            not (missing_top or extra_top or missing_row or extra_row),
    }


