#: How many integer comparisons the certified route actually performed. Without
#: this the claim "no floating point is evaluated" is unfalsifiable from the
#: report: swapping the integer route for the mpmath one produces the SAME
#: partial quotients, so every other field agrees and the two-method agreement
#: check confirms a comparison of a thing with itself.
_COMPARISONS = {"count": 0}


def _cmp_pow(a2: int, a3: int) -> int:
    """Sign of 2^a2 * 3^a3 - 1, for integer exponents of either sign."""
    _COMPARISONS["count"] += 1
    if a2 >= 0 and a3 >= 0:
        return 0 if (a2 == 0 and a3 == 0) else 1
    if a2 <= 0 and a3 <= 0:
        return 0 if (a2 == 0 and a3 == 0) else -1
    if a2 > 0:                       # compare 2^a2 against 3^(-a3)
        left, right = 1 << a2, 3 ** (-a3)
    else:                            # compare 3^a3 against 2^(-a2)
        left, right = 3 ** a3, 1 << (-a2)
    return (left > right) - (left < right)


def cmp_pow_self_test() -> dict:
    """The primitive everything else rests on, on cases decided by hand.

    2^19 = 524288 < 531441 = 3^12 is the classic near-miss that makes 19/12 a
    convergent of log_2 3; 2^8 = 256 > 243 = 3^5 is the other side.
    """
    cases = [
        ("2^19 < 3^12", (19, -12), -1),
        ("2^8 > 3^5", (8, -5), 1),
        ("2^1 < 3^1", (1, -1), -1),
        ("2^2 > 3^1", (2, -1), 1),
        ("2^0 * 3^0 == 1", (0, 0), 0),
        ("2^-1 < 1", (-1, 0), -1),
        ("3^1 > 1", (0, 1), 1),
    ]
    rows = {name: _cmp_pow(*args) == want for name, args, want in cases}
    return {"cases": rows, "all_correct": all(rows.values())}


def exact_continued_fraction(max_terms: int, budget_seconds: float) -> dict:
    """Partial quotients of log_2 3, decided by integer comparisons only.

    State is `log_u v` with u, v = 2^a 3^b, so `floor(log_u v)` is the largest k
    with `u^k <= v`, i.e. a comparison of two integer powers. No logarithm and no
    floating point is evaluated anywhere in this function.
    """
    u = (1, 0)          # u = 2
    v = (0, 1)          # v = 3
    terms, started, stopped = [], time.time(), None
    for _ in range(max_terms):
        if time.time() - started > budget_seconds:
            stopped = "time budget"
            break
        # Largest k with u^k <= v, by doubling then bisection. Incrementing k
        # one at a time cost 56 comparisons for the partial quotient 55, each on
        # ten-million-bit integers; this costs about twelve. The budget still
        # binds inside the search, because one comparison at this size is not
        # cheap either.
        def fits(k: int) -> bool:
            return _cmp_pow(k * u[0] - v[0], k * u[1] - v[1]) <= 0

        hi = 1
        while True:
            if time.time() - started > budget_seconds:
                stopped = "time budget, mid-partial-quotient"
                break
            if not fits(hi):
                break
            hi *= 2
            if hi > 10 ** 7:                         # pragma: no cover
                stopped = "runaway partial quotient"
                break
        if stopped:
            break
        low = hi // 2                                # fits(low) is known true
        while hi - low > 1:
            if time.time() - started > budget_seconds:
                stopped = "time budget, mid-partial-quotient"
                break
            mid = (low + hi) // 2
            if fits(mid):
                low = mid
            else:
                hi = mid
        if stopped:
            break
        k = low
        terms.append(k)
        u, v = (v[0] - k * u[0], v[1] - k * u[1]), u
        if u == (0, 0):                              # pragma: no cover
            stopped = "terminated"
            break
    return {"terms": terms, "stopped_because": stopped or "reached max_terms",
            "seconds": round(time.time() - started, 2),
            "integer_comparisons": _COMPARISONS["count"]}


def convergents_from_terms(terms: list[int]) -> list[tuple[int, int, int]]:
    """(index, p, q) for each convergent of the given partial quotients."""
    p_prev, p_cur = 0, 1
    q_prev, q_cur = 1, 0
    out = []
    for i, a in enumerate(terms):
        p_prev, p_cur = p_cur, a * p_cur + p_prev
        q_prev, q_cur = q_cur, a * q_cur + q_prev
        out.append((i, p_cur, q_cur))
    return out


def mpmath_continued_fraction(count: int) -> list[int]:
    """The same sequence at four times the artifact's precision. Independent
    only in arithmetic, not in method -- which is why the integer route above
    exists and is the one that certifies."""
    with mp.workdps(WORKING_DPS):
        x = mp.log(3, 2)
        terms = []
        for _ in range(count):
            a = int(mp.floor(x))
            terms.append(a)
            frac = x - a
            if frac == 0:                            # pragma: no cover
                break
            x = 1 / frac
    return terms


def check_continued_fraction(data: dict, budget: float) -> dict:
    rows = data["upper_convergent_diagnostics"]
    primitive = cmp_pow_self_test()
    before = _COMPARISONS["count"]
    exact = exact_continued_fraction(max_terms=26, budget_seconds=budget)
    certified_terms = exact["terms"]
    high = mpmath_continued_fraction(len(certified_terms) + 8)

    agree_upto = 0
    for a, b in zip(certified_terms, high):
        if a != b:
            break
        agree_upto += 1

    conv_exact = convergents_from_terms(certified_terms)
    conv_high = convergents_from_terms(high)
    by_index_exact = {i: (p, q) for i, p, q in conv_exact}
    by_index_high = {i: (p, q) for i, p, q in conv_high}

    largest_certified_q = max((q for _, _, q in conv_exact), default=0)

    row_checks, disagreements = [], []
    for row in rows:
        idx = row["index"]
        source = "integer-certified" if idx + 1 < len(certified_terms) else "400 dps"
        table = by_index_exact if source == "integer-certified" else by_index_high
        got = table.get(idx)
        nxt = table.get(idx + 1)
        ok = (got is not None and nxt is not None
              and got == (row["p"], row["q"])
              and nxt[1] == row["q_next"]
              and (certified_terms if source == "integer-certified" else high)[idx]
              == row["partial_quotient"]
              and (certified_terms if source == "integer-certified" else high)[idx + 1]
              == row["next_partial_quotient"])
        row_checks.append({"index": idx, "q": row["q"], "decided_by": source,
                           "agrees": bool(ok)})
        if not ok:
            disagreements.append({"index": idx, "shipped": [row["p"], row["q"],
                                                            row["q_next"]],
                                  "recomputed": [got, nxt]})

    return {
        "cmp_pow_self_test": primitive,
        "integer_comparisons_performed": exact["integer_comparisons"] - before,
        "terms_certified_by_integer_comparison": len(certified_terms),
        "largest_denominator_certified": largest_certified_q,
        "certification_stopped_because": exact["stopped_because"],
        "certification_seconds": exact["seconds"],
        "certified_partial_quotients": certified_terms,
        "the_two_methods_agree_on_the_first_n_terms": agree_upto,
        "the_two_methods_agree_everywhere_both_ran": agree_upto == len(certified_terms),
        "rows": row_checks,
        "rows_integer_certified": sum(1 for r in row_checks
                                      if r["decided_by"] == "integer-certified"),
        "rows_cross_checked_only": sum(1 for r in row_checks
                                       if r["decided_by"] != "integer-certified"),
        "disagreements": disagreements,
    }


