# section 8 — the renewal geometry: sparsity exponent and interval colouring
# ---------------------------------------------------------------------------

def check_renewal_geometry(theta: Fraction, sigma: Fraction) -> dict:
    with mp.workdps(60):
        th = mp.mpf(theta.numerator) / theta.denominator

        # sum_{j<=R} (2j+1)^theta  >=  ((2R+1)^{1+theta} - 1) / (2(1+theta))
        integral_fail, ratios = 0, []
        total = mp.mpf(0)
        for R in range(1, 3001):
            total += (2 * R + 1) ** th
            bound = ((2 * R + 1) ** (1 + th) - 1) / (2 * (1 + th))
            if total < bound:
                integral_fail += 1
            if R in (100, 500, 1000, 2000, 3000):
                ratios.append({"R": R, "sum_over_R^(1+theta)":
                               mp.nstr(total / R ** (1 + th), 10)})
        limit = 2 ** th / (1 + th)

        # the exponent identity the sparsity theorem turns on, exactly
        exponent_identity = (sigma * (1 + theta) == 1)
        # N >= c R^{1+theta}  =>  R <= (N/c)^sigma, as an exponent statement
        exponent_transfer = (Fraction(1) / (1 + theta) == sigma)

    # interval colouring: an interval family splits into (max overlap) disjoint
    # families, which is what section 15 uses. Checked in both directions.
    rng = random.Random(4711)
    colour_rows, colour_bad, witnessed = [], 0, 0
    overlaps_seen = set()
    for trial in range(300):
        n = rng.randint(2, 40)
        ivs = []
        for _ in range(n):
            s = rng.randint(0, 200)
            ivs.append((s, s + rng.randint(1, 60)))
        # max overlap
        events = sorted([(s, 1) for s, _ in ivs] + [(e, -1) for _, e in ivs],
                        key=lambda t: (t[0], t[1]))
        cur = omega = 0
        for _, delta in events:
            cur += delta
            omega = max(omega, cur)
        # greedy sweep colouring by left endpoint
        free, used, active = [], 0, []
        for s, e in sorted(ivs):
            active = [(end, col) for end, col in active if end > s]
            taken = {col for _, col in active}
            col = next((c for c in range(used + 1) if c not in taken), used)
            used = max(used, col + 1)
            active.append((e, col))
        overlaps_seen.add(omega)
        if used != omega:
            colour_bad += 1
        if omega >= 2:
            witnessed += 1
        if trial < 5:
            colour_rows.append({"intervals": n, "max_overlap": omega,
                                "colours_greedy_used": used})
    return {
        "sum_bound_failures": integral_fail,
        "sum_over_R^(1+theta)": ratios,
        "predicted_limit_2^theta/(1+theta)": mp.nstr(limit, 10),
        "sigma*(1+theta) == 1 exactly": bool(exponent_identity),
        "sigma == 1/(1+theta) exactly": bool(exponent_transfer),
        "colouring_trials": 300,
        "trials_where_colours_used_exceeded_max_overlap": colour_bad,
        "trials_with_a_genuine_overlap": witnessed,
        "distinct_max_overlaps_seen": len(overlaps_seen),
        "examples": colour_rows,
    }


