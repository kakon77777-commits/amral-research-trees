# section 6 — the two second-order expansion coefficients
# ---------------------------------------------------------------------------

def check_expansion_coefficients() -> dict:
    """Section 9 and section 16, tested where a wrong SECOND coefficient shows.

    Both are asymptotic expansions. Checking the constants only tests the symbols;
    the scaled residual tests the expansion. It goes to zero when the coefficient
    is right and to a nonzero constant when it is not, so the same probe both
    confirms the round's value and would reject a neighbouring one.
    """
    with mp.workdps(WORKING_DPS):
        ln2 = mp.log(2)
        eta = 1 / (6 * ln2)
        kappa = 1 / (12 * mp.sqrt(2))
        c0, c1 = ln2 / eta, ln2 * kappa / eta ** 2

        # --- section 9: ln2/(eta q - kappa sqrt q)  ==  c0/q + c1/q^{3/2} + O(q^-2)
        def residual9(q, second):
            q = mp.mpf(q)
            exact = ln2 / (eta * q - kappa * mp.sqrt(q))
            claimed = c0 / q + second / q ** mp.mpf("1.5")
            return (exact - claimed) * q ** mp.mpf("1.5")

        s9 = [{"q": "1e%d" % k,
               "residual_with_the_round_s_c1": mp.nstr(residual9(mp.mpf(10) ** k, c1), 6),
               "residual_with_c1_wrong_by_1pct":
                   mp.nstr(residual9(mp.mpf(10) ** k, c1 * mp.mpf("1.01")), 6)}
              for k in (4, 6, 8, 10, 12)]
        r_right9 = abs(residual9(mp.mpf(10) ** 12, c1))
        r_wrong9 = abs(residual9(mp.mpf(10) ** 12, c1 * mp.mpf("1.01")))

        # --- section 16: q >= A/eta + (kappa/eta^{3/2}) sqrt A + o(sqrt A)
        coeff16 = kappa / eta ** mp.mpf("1.5")

        def residual16(A, second):
            A = mp.mpf(A)
            x = (kappa + mp.sqrt(kappa ** 2 + 4 * eta * A)) / (2 * eta)
            return (x ** 2 - A / eta - second * mp.sqrt(A)) / mp.sqrt(A)

        s16 = [{"A": "1e%d" % k,
                "residual_with_the_round_s_coefficient":
                    mp.nstr(residual16(mp.mpf(10) ** k, coeff16), 6),
                "residual_with_it_wrong_by_1pct":
                    mp.nstr(residual16(mp.mpf(10) ** k, coeff16 * mp.mpf("1.01")), 6)}
               for k in (4, 6, 8, 10, 12)]
        r_right16 = abs(residual16(mp.mpf(10) ** 12, coeff16))
        r_wrong16 = abs(residual16(mp.mpf(10) ** 12, coeff16 * mp.mpf("1.01")))

        # the quadratic root the section-16 expansion approximates, checked exactly
        A = mp.mpf(10) ** 9
        x = (kappa + mp.sqrt(kappa ** 2 + 4 * eta * A)) / (2 * eta)
        root_ok = abs(eta * x ** 2 - kappa * x - A) < mp.mpf(10) ** (-WORKING_DPS + 30)

        near9 = abs(residual9(mp.mpf(10) ** 4, c1))
        near16 = abs(residual16(mp.mpf(10) ** 4, coeff16))
        near9w = abs(residual9(mp.mpf(10) ** 4, c1 * mp.mpf("1.01")))
        near16w = abs(residual16(mp.mpf(10) ** 4, coeff16 * mp.mpf("1.01")))

    return {
        "section_9_residual_falls_by_at_least_1000x_from_1e4_to_1e12":
            bool(r_right9 * 1000 < near9),
        "section_16_residual_falls_by_at_least_1000x_from_1e4_to_1e12":
            bool(r_right16 * 1000 < near16),
        "section_9_wrong_coefficient_does_not_vanish":
            bool(r_wrong9 > near9w / 2),
        "section_16_wrong_coefficient_does_not_vanish":
            bool(r_wrong16 > near16w / 2),
        "section_9_scaled_residuals": s9,
        "section_16_scaled_residuals": s16,
        "section_9_residual_at_1e12": {"round_s_value": mp.nstr(r_right9, 6),
                                       "off_by_1pct": mp.nstr(r_wrong9, 6)},
        "section_16_residual_at_1e12": {"round_s_value": mp.nstr(r_right16, 6),
                                        "off_by_1pct": mp.nstr(r_wrong16, 6)},
        "section_9_coefficient_is_discriminated": bool(r_right9 < r_wrong9 / 100),
        "section_16_coefficient_is_discriminated": bool(r_right16 < r_wrong16 / 100),
        "the_quadratic_root_solves_its_equation": bool(root_ok),
        "section_16_coefficient": mp.nstr(coeff16, 16),
    }


